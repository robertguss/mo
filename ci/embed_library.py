#!/usr/bin/env python3
"""Embed lib/*.mo into a generated C header for single-binary portability."""
import json
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
parts = ["/* Generated by ci/embed_library.py; do not edit. */\n"]
sources = []
for index, raw in enumerate(sys.argv[2:]):
    path = pathlib.Path(raw)
    rel = path.name if path.parts[0] != "lib" else "/".join(path.parts[1:])
    data = path.read_bytes()
    symbol = f"mo_library_source_{index}"
    parts.append(f"static const unsigned char {symbol}[] = {{\n")
    for start in range(0, len(data), 24):
        parts.append("    " + ",".join(str(b) for b in data[start:start + 24]) + ",\n")
    parts.append("    0\n};\n")
    sources.append(f"    {{{json.dumps(rel)}, {symbol}, {len(data)}}},\n")
parts.append("static const struct mo_embedded_source mo_library_sources[] = {\n")
parts.extend(sources)
parts.append("};\n")
parts.append(
    "static const struct mo_embedded_library mo_embedded_lib = {\n"
    f"    mo_library_sources, {len(sources)}\n"
    "};\n"
)
encoded = "".join(parts).encode("ascii")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_bytes() != encoded:
    out.write_bytes(encoded)
