#!/usr/bin/env python3
"""Embed the version-matched documents as bytes, without C string-size limits."""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
out = pathlib.Path(sys.argv[1])
parts = ["/* Generated by ci/embed_docs.py; do not edit. */\n"]
for name, path in (("reference", "docs/reference/README.md"), ("guide", "docs/agent-guide.md")):
    source = root / path
    data = b""
    if source.exists():
        with source.open("rb") as stream:
            data = stream.read(4 * 1024 * 1024 + 1)
    if len(data) > 4 * 1024 * 1024:
        raise SystemExit(f"{path}: embedded document exceeds 4 MiB")
    parts.append(f"static const unsigned char mo_embedded_{name}[] = {{\n")
    for start in range(0, len(data), 24):
        parts.append("    " + ",".join(str(b) for b in data[start:start + 24]) + ",\n")
    parts.append("    0\n};\n")
    parts.append(f"static const size_t mo_embedded_{name}_size = {len(data)};\n")
library = bytes(root / "lib")
if len(library) > 4096:
    raise SystemExit("build's library path exceeds 4096 bytes")
parts.append('static const char mo_library_path[] = "' + "".join(f"\\{b:03o}" for b in library) + '";\n')
data = "".join(parts).encode("ascii")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_bytes() != data:
    out.write_bytes(data)
