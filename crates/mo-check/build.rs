#![forbid(unsafe_code)]

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

type BuildResult<T> = Result<T, String>;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    run().map_err(|msg| -> Box<dyn std::error::Error> { msg.into() })
}

fn run() -> BuildResult<()> {
    let manifest_dir = PathBuf::from(
        env::var("CARGO_MANIFEST_DIR").map_err(|e| format!("CARGO_MANIFEST_DIR: {e}"))?,
    );
    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .ok_or_else(|| "crates/mo-check must live two levels under repo root".to_string())?;
    let lib_dir = repo_root.join("lib");
    if !lib_dir.is_dir() {
        return Err(format!(
            "missing standard library directory: {}",
            lib_dir.display()
        ));
    }

    let mut files = Vec::new();
    let mut dirs = Vec::new();
    collect_library_files(&lib_dir, &lib_dir, &mut dirs, &mut files)?;

    dirs.sort();
    for dir in &dirs {
        println!("cargo:rerun-if-changed={}", dir.display());
    }

    // Sort by relative path bytes to match `Makefile`'s `$(sort $(wildcard lib/*.mo lib/*/*.mo))`
    // and `ci/embed_library.py` exactly.
    files.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    for (_, abs) in &files {
        println!("cargo:rerun-if-changed={}", abs.display());
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?);
    let mut out = String::new();
    writeln!(
        &mut out,
        "// Generated by crates/mo-check/build.rs; do not edit.\n"
    )
    .map_err(fmt_err)?;
    writeln!(
        &mut out,
        "pub const DEFAULT_LIBRARY_ROOT: &str = {:?};\n",
        lib_dir.to_string_lossy()
    )
    .map_err(fmt_err)?;
    writeln!(
        &mut out,
        "pub const EMBEDDED_LIBRARY_FILES: &[EmbeddedSource] = &["
    )
    .map_err(fmt_err)?;
    for (rel, abs) in &files {
        writeln!(&mut out, "    EmbeddedSource {{").map_err(fmt_err)?;
        writeln!(&mut out, "        path: {rel:?},").map_err(fmt_err)?;
        writeln!(
            &mut out,
            "        bytes: include_bytes!({:?}),",
            abs.to_string_lossy()
        )
        .map_err(fmt_err)?;
        writeln!(&mut out, "    }},").map_err(fmt_err)?;
    }
    writeln!(&mut out, "];").map_err(fmt_err)?;

    let out_path = out_dir.join("embedded_library.rs");
    let unchanged = fs::read_to_string(&out_path).ok().as_deref() == Some(out.as_str());
    if !unchanged {
        fs::write(&out_path, out).map_err(|e| format!("write {}: {e}", out_path.display()))?;
    }
    Ok(())
}

fn collect_library_files(
    lib_root: &Path,
    dir: &Path,
    dirs: &mut Vec<PathBuf>,
    files: &mut Vec<(String, PathBuf)>,
) -> BuildResult<()> {
    dirs.push(dir.to_path_buf());
    let entries = fs::read_dir(dir).map_err(|e| format!("read_dir {}: {e}", dir.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("read_dir entry {}: {e}", dir.display()))?;
        let path = entry.path();
        let meta = fs::symlink_metadata(&path)
            .map_err(|e| format!("symlink_metadata {}: {e}", path.display()))?;
        if meta.file_type().is_dir() {
            collect_library_files(lib_root, &path, dirs, files)?;
        } else if (meta.file_type().is_file() || meta.file_type().is_symlink())
            && path.extension().and_then(|e| e.to_str()) == Some("mo")
        {
            let rel = path
                .strip_prefix(lib_root)
                .map_err(|e| format!("strip_prefix {}: {e}", path.display()))?;
            let rel_str = rel
                .components()
                .map(|c| c.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            files.push((rel_str, path));
        }
    }
    Ok(())
}

fn fmt_err(e: std::fmt::Error) -> String {
    format!("format embedded_library.rs: {e}")
}
