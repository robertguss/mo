#![forbid(unsafe_code)]

//! Embeds `docs/reference/README.md` and `docs/agent-guide.md` (with the 4 MiB
//! cap matching `ci/embed_docs.py`) and records the repository `lib/` path for
//! default library root detection.

use std::env;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const MAX_EMBEDDED_DOC_BYTES: usize = 4 * 1024 * 1024;

fn main() -> ExitCode {
    if let Err(msg) = run() {
        let _ = writeln!(std::io::stderr(), "mo-cli build.rs: {msg}");
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

fn run() -> Result<(), String> {
    let manifest_dir = env::var_os("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| "CARGO_MANIFEST_DIR not set".to_string())?;
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| "OUT_DIR not set".to_string())?;

    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .ok_or_else(|| "could not locate repository root from CARGO_MANIFEST_DIR".to_string())?;

    let guide_rel = Path::new("../../docs/agent-guide.md");
    let ref_rel = Path::new("../../docs/reference/README.md");
    println!("cargo:rerun-if-changed={}", guide_rel.display());
    println!("cargo:rerun-if-changed={}", ref_rel.display());

    let guide_path = repo_root.join("docs/agent-guide.md");
    let ref_path = repo_root.join("docs/reference/README.md");
    let lib_path = repo_root.join("lib");

    check_doc(&guide_path, "docs/agent-guide.md")?;
    check_doc(&ref_path, "docs/reference/README.md")?;

    let guide_abs = fs::canonicalize(&guide_path)
        .map_err(|e| format!("could not resolve {}: {e}", guide_path.display()))?;
    let ref_abs = fs::canonicalize(&ref_path)
        .map_err(|e| format!("could not resolve {}: {e}", ref_path.display()))?;

    let guide_lit = rust_string_literal(&guide_abs.to_string_lossy());
    let ref_lit = rust_string_literal(&ref_abs.to_string_lossy());
    let lib_lit = rust_string_literal(&lib_path.to_string_lossy());

    let generated = format!(
        "// Generated by crates/mo-cli/build.rs — do not edit.\n\
         /// Embedded `docs/agent-guide.md` (`mo guide`).\n\
         pub const MO_EMBEDDED_GUIDE: &str = include_str!({guide_lit});\n\
         /// Embedded `docs/reference/README.md` (`mo guide --reference`).\n\
         pub const MO_EMBEDDED_REFERENCE: &str = include_str!({ref_lit});\n\
         /// Repository `lib/` path recorded at build time (`mo_default_library_root`).\n\
         pub const DEFAULT_BUILD_LIBRARY_ROOT: &str = {lib_lit};\n"
    );

    let dest = out_dir.join("embedded_docs.rs");
    fs::write(&dest, generated).map_err(|e| format!("could not write {}: {e}", dest.display()))?;
    Ok(())
}

fn check_doc(path: &Path, label: &str) -> Result<(), String> {
    let bytes = fs::read(path).map_err(|e| format!("could not read {label}: {e}"))?;
    if bytes.len() > MAX_EMBEDDED_DOC_BYTES {
        return Err(format!(
            "{label} is {} bytes, exceeding the 4 MiB limit ({MAX_EMBEDDED_DOC_BYTES})",
            bytes.len()
        ));
    }
    if std::str::from_utf8(&bytes).is_err() {
        return Err(format!("{label} is not valid UTF-8"));
    }
    Ok(())
}

fn rust_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
